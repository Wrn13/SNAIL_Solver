"""Eq. (3) for the gate: U(t_g, 0) = e^{-i Lambda(t_g)} V(t_g, 0) e^{+i Lambda(0)},
where V is generated by the effective Hamiltonian F(t).

`qobjevo` builds F(t) for QuTiP from a fitted `EffectiveModel`. The pulse supplies
eta(t) = cpl._eta(tone, t), which carries the envelope, amplitude, chirp phase and phi_p.
A carrier offset dw = w_p - |w_b - w_a| multiplies a term with s pump quanta by
e^{-i s 2pi dw t}, exactly as a chirp does. In the displaced frame F(t) also gets the
non-adiabatic remainder of the displacement, -i G_k'(t) e^{-i Omega_k t} s^dag + h.c.

`replay` reproduces the pipeline's projected propagator and leakage-aware iSWAP fidelity.
With kicks it applies (3) at both ends, using Lambda at eta = 0 since the pulse vanishes
there. `install` hands F(t) to the unchanged pipeline (tune-up, chevrons, scoring) by
replacing ``ZhouCoupler.to_qutip_hamiltonian`` in this process and its forks.
"""
from __future__ import annotations

import cmath
import os
from typing import Any, Callable, Dict, Optional, Tuple

import numpy as np
import scipy.sparse as sps

from floquet.fourier import COUPLER, Signature, carrier
from floquet.model import EffectiveModel, Term, for_coupler

TWO_PI = 2.0 * np.pi


def qobjevo(cpl, model: EffectiveModel, keep: Optional[Callable[[Term], bool]] = None,
            scale: Optional[Dict[Tuple[int, Signature], float]] = None, h_ns: float = 1e-3):
    """F(t) in rad/ns as a QuTiP QobjEvo on `cpl`'s Fock space.

    `keep` selects terms. `scale` multiplies the terms of given (order, signature) groups,
    which the sensitivity analysis uses. Each call is one sparse mat-vec: a fixed map from
    the term coefficients to the data of F(t) on the union sparsity pattern."""
    import qutip as qt
    if len(cpl._pump_tones) != 1:
        raise ValueError("a single pump tone is supported")
    tone = cpl._pump_tones[0]
    t_end = getattr(tone.envelope, "t_g", None)
    if t_end:
        peak = max(abs(cpl._eta(tone, t)) for t in np.linspace(0.0, t_end, 401))
        if peak > model.x_max * (1 + 1e-6):
            raise ValueError(f"pulse peak |eta| = {peak:.3f} is beyond the fitted range "
                             f"{model.x_max}")
    dw = float(tone.w_p_GHz) - model.pump_GHz
    dims = [list(cpl.dims), list(cpl.dims)]
    dim = int(np.prod(cpl.dims))
    scale = scale or {}
    mats, K, Sx, OM = [], [], [], []
    for tm in model.select(keep):
        mats.append(tm.matrix * scale.get((tm.order, tm.sig), 1.0))
        K.append(tm.power + abs(tm.s))
        Sx.append(tm.s)
        OM.append(TWO_PI * (tm.carrier_GHz + tm.s * dw))
    n_terms = len(mats)
    s_mat = sps.kron(sps.identity(cpl.dims[0] * cpl.dims[1]),
                     sps.diags(np.sqrt(np.arange(1, cpl.dims[2])), 1), format="csr")
    kicks = sorted(model.displacement)
    for _ in kicks:
        mats.append(s_mat.T.conj().tocsr())
        mats.append(s_mat)
    union = sum(abs(m) for m in mats).tocsr()
    union.sort_indices()
    pos = {(r, c): q for q, (r, c) in enumerate(zip(*union.nonzero()))}
    rows, cols, vals = [], [], []
    for j, m in enumerate(mats):
        m = m.tocoo()
        for r, c, v in zip(m.row, m.col, m.data):
            rows.append(pos[(r, c)])
            cols.append(j)
            vals.append(v)
    A = sps.csr_matrix((vals, (rows, cols)), shape=(union.nnz, len(mats)))
    pattern = union.nonzero()
    K, Sx, OM = np.array(K, float), np.array(Sx, float), np.array(OM, float)
    om_k = np.array([TWO_PI * (k * model.pump_GHz - model.freqs_GHz[COUPLER]) for k in kicks])

    def G(t: float) -> np.ndarray:
        e = cpl._eta(tone, t)
        x = abs(e)
        u = e / x if x > 0 else 1.0
        return np.array([model.b_at(k, x) * u ** k * cmath.exp(-1j * TWO_PI * k * dw * t)
                         for k in kicks], complex)

    def H(t: float, *args, **kw):
        e = cpl._eta(tone, t)
        x = abs(e)
        u = e / x if x > 0 else 1.0 + 0j
        c = np.empty(len(mats), complex)
        c[:n_terms] = TWO_PI * x ** K * u ** Sx * np.exp(-1j * OM * t)
        if kicks:
            dG = (G(t + h_ns) - G(t - h_ns)) / (2 * h_ns)
            kk = -1j * dG * np.exp(-1j * om_k * t)
            c[n_terms::2] = kk
            c[n_terms + 1::2] = np.conj(kk)
        return qt.Qobj(sps.csr_matrix((A @ c, pattern), shape=(dim, dim)), dims=dims)
    return qt.QobjEvo(H)


def kick_operator(model: EffectiveModel, t: float, upto: int) -> Optional[np.ndarray]:
    """Lambda^[upto](t) at eta = 0, dense: the frame change of (3) at the pulse ends."""
    out = None
    for n in range(1, upto + 1):
        for sig, M in model.kick.get(n, {}).items():
            term = M.toarray() * np.exp(-2j * np.pi * carrier(sig, model.freqs_GHz) * t)
            out = term if out is None else out + term
    return out


def replay(cpl, H, t_g: float, kicks: Optional[Tuple[np.ndarray, np.ndarray]] = None,
           atol: float = 1e-10, rtol: float = 1e-8, nsteps: int = 500000) -> Dict[str, Any]:
    """The pipeline's 4x4 projected propagator and leakage-aware iSWAP fidelity for H.
    With ``kicks = (Lambda(0), Lambda(t_g))`` the kets are e^{+i Lambda(0)}|k> initially
    and e^{-i Lambda(t_g)}|psi> finally, as in (3)."""
    import qutip as qt
    from scipy.linalg import expm
    options = cpl._qutip_options(atol, rtol, nsteps)
    idx = cpl._subspace_indices(0, 1)
    dims = [list(cpl.dims), [1] * cpl.n_modes]
    K0 = expm(1j * kicks[0]) if kicks else None
    K1 = expm(-1j * kicks[1]) if kicks else None
    tlist = np.linspace(0.0, t_g, int(np.clip(np.ceil(t_g / 5.0), 1, 4000)) + 1)
    U = np.zeros((4, 4), complex)
    for col, start in enumerate(idx):
        v = np.zeros(cpl.dim, complex)
        v[start] = 1.0
        if K0 is not None:
            v = K0 @ v
        psi = qt.sesolve(H, qt.Qobj(v.reshape(-1, 1), dims=dims), tlist,
                         options=options).states[-1].full().ravel()
        if K1 is not None:
            psi = K1 @ psi
        U[:, col] = psi[idx]
    F, leak = cpl._iswap_fidelity_from_U(U, True)
    return {"F_avg": F, "leakage": leak, "U": U}


def gate_distance(U: np.ndarray, U_ref: np.ndarray) -> float:
    """1 - leakage-aware average fidelity of the 4x4 block U against U_ref, with U_ref
    replaced by its closest unitary: how differently two models make the same pulse act."""
    u, _, vh = np.linalg.svd(U_ref)
    W = u @ vh
    return 1.0 - float((abs(np.trace(W.conj().T @ U)) ** 2 + np.real(np.trace(U.conj().T @ U)))
                       / 20.0)


def susceptibility(U_plus: np.ndarray, U_minus: np.ndarray, eps: float) -> float:
    """Leading-order average infidelity per (d ln c)^2 between gates with one term scaled
    by (1 +/- eps): (|G|^2 - |Tr G|^2 / d) / (d + 1), with G = U0^dag dU/d ln c."""
    dU = (U_plus - U_minus) / (2 * eps)
    u, _, vh = np.linalg.svd((U_plus + U_minus) / 2)
    G = (u @ vh).conj().T @ dU
    return float((np.linalg.norm(G) ** 2 - abs(np.trace(G)) ** 2 / 4) / 5)


# --------------------------------------------------------------------------- pipeline hook
_STATE: Dict[str, Any] = {}


def install(*, cache_dir: Optional[str] = None, keep=None, **model_kw) -> None:
    """Make every ZhouCoupler in this process (and its forks) solve F(t) of the model
    `for_coupler(cpl, **model_kw)` instead of the full H_I."""
    from snail_solver import zhou_coupler as Z
    if "orig" not in _STATE:
        _STATE["orig"] = Z.ZhouCoupler.to_qutip_hamiltonian
    _STATE.update(cache_dir=cache_dir, keep=keep, kw=model_kw)
    os.environ["FVV_MODEL"] = repr(model_kw)

    def to_qutip_hamiltonian(self, cutoff_GHz: float = np.inf, sparse: bool = True):
        model = for_coupler(self, cache_dir=_STATE["cache_dir"], **_STATE["kw"])
        return qobjevo(self, model, keep=_STATE["keep"])
    Z.ZhouCoupler.to_qutip_hamiltonian = to_qutip_hamiltonian


def uninstall() -> None:
    from snail_solver import zhou_coupler as Z
    if "orig" in _STATE:
        Z.ZhouCoupler.to_qutip_hamiltonian = _STATE.pop("orig")
